import { promises as fs } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

/** Port the compose file publishes postgres on (docker/docker-compose.yml). */
const DB_HOST_PORT = 5432;

/** Copies every config/environment-variables/.env*.example to a .dev twin. */
export async function copyExamples(envDir) {
  const entries = await fs.readdir(envDir, { withFileTypes: true });

  const matches = entries
    .filter((e) => e.isFile())
    .map((e) => e.name)
    .filter((name) => name.startsWith(".env") && name.endsWith(".example"));

  for (const file of matches) {
    const src = path.join(envDir, file);
    const dest = path.join(envDir, file.replace(/\.example$/, ".dev"));

    await fs.copyFile(src, dest);
    console.log(`Created ${path.basename(dest)}`);
  }

  return matches.length;
}

/** Minimal dotenv parser: KEY=value lines, optional surrounding quotes, # comments. */
export function parseEnv(text) {
  const env = {};

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const eq = line.indexOf("=");
    if (eq === -1) continue;

    const key = line.slice(0, eq).trim();
    const value = line.slice(eq + 1).trim().replace(/^(["'])(.*)\1$/, "$2");
    env[key] = value;
  }

  return env;
}

/**
 * `npm run seed` runs prisma on the host, and prisma.config.ts reads
 * backend/.env through dotenv. The containers reach postgres as `db`, but the
 * host reaches it on localhost via the published port, so the URL is derived
 * here from the same credentials the db container is started with.
 */
export function buildSeedEnv(dbEnv, backendEnv = {}) {
  const { POSTGRES_USER: user, POSTGRES_PASSWORD: password, POSTGRES_DB: db } = dbEnv;

  const missing = ["POSTGRES_USER", "POSTGRES_PASSWORD", "POSTGRES_DB"].filter((k) => !dbEnv[k]);
  if (missing.length > 0) {
    throw new Error(`.env.db.dev is missing ${missing.join(", ")}; fill it in and rerun.`);
  }

  const url = `postgresql://${encodeURIComponent(user)}:${encodeURIComponent(password)}@localhost:${DB_HOST_PORT}/${encodeURIComponent(db)}`;

  // The seed also creates the platform super admin from these (see backend/src/lib/seed-admin.ts).
  const seedAdmin = Object.entries(backendEnv)
    .filter(([key]) => key.startsWith("SEED_ADMIN_"))
    .map(([key, value]) => `${key}=${value}`);

  return [
    "# Generated by `npm run create-envs` from config/environment-variables/.env.db.dev",
    "# and the SEED_ADMIN_* values in .env.backend.dev.",
    "# Used only when running prisma on the host (`npm run seed`). Inside Docker the",
    "# backend gets these from .env.backend.dev instead.",
    `DATABASE_URL=${url}`,
    ...seedAdmin,
    "",
  ].join("\n");
}

export async function writeSeedEnv(envDir, backendDir) {
  const dbEnv = parseEnv(await fs.readFile(path.join(envDir, ".env.db.dev"), "utf8"));
  const backendEnv = parseEnv(await fs.readFile(path.join(envDir, ".env.backend.dev"), "utf8"));
  const dest = path.join(backendDir, ".env");

  await fs.writeFile(dest, buildSeedEnv(dbEnv, backendEnv));
  console.log(`Created ${path.relative(path.dirname(backendDir), dest)} (for npm run seed)`);
}

async function main() {
  const root = process.cwd();
  const envDir = path.join(root, "config", "environment-variables");

  const copied = await copyExamples(envDir);
  if (copied === 0) {
    console.log("No .env*.example files found.");
    return;
  }

  await writeSeedEnv(envDir, path.join(root, "backend"));
}

const runDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (runDirectly) {
  main().catch((err) => {
    console.error("Failed to create .dev env files:", err.message ?? err);
    process.exit(1);
  });
}
